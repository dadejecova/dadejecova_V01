'use client';

import { useState } from 'react';
import Link from 'next/link';

interface Question {
  id: number;
  question: string;
  options: string[];
  correct_index: number;
  explanation: string;
}

interface QuizData {
  questions: Question[];
}

interface LessonQuizProps {
  lessonSlug: string;
  isLoggedIn: boolean;
}

export default function LessonQuiz({ lessonSlug, isLoggedIn }: LessonQuizProps) {
  const [quiz, setQuiz] = useState<QuizData | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [quizStarted, setQuizStarted] = useState(false);
  
  // Game states
  const [currentIdx, setCurrentIdx] = useState(0);
  const [selectedOpt, setSelectedOpt] = useState<number | null>(null);
  const [isChecked, setIsChecked] = useState(false);
  const [score, setScore] = useState(0);
  const [quizCompleted, setQuizCompleted] = useState(false);

  const fetchQuiz = async () => {
    setIsLoading(true);
    setError(null);
    setQuizStarted(true);
    try {
      const token = localStorage.getItem('access_token');
      if (!token) {
        setError('You must log in to take the quiz.');
        setIsLoading(false);
        return;
      }

      const res = await fetch(`${process.env.NEXT_PUBLIC_API_URL}/lessons/${lessonSlug}/quiz/`, {
        headers: {
          'Authorization': `Bearer ${token}`
        }
      });

      if (res.ok) {
        const data = await res.json();
        setQuiz(data);
      } else {
        const errData = await res.json().catch(() => ({}));
        setError(errData.error || 'Failed to connect to the AI server.');
      }
    } catch (err) {
      console.error('Error fetching quiz:', err);
      setError('An unexpected error occurred while generating the quiz.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleOptionSelect = (idx: number) => {
    if (isChecked) return; // lock selection once submitted
    setSelectedOpt(idx);
  };

  const handleCheckAnswer = () => {
    if (selectedOpt === null || !quiz) return;
    setIsChecked(true);
    if (selectedOpt === quiz.questions[currentIdx].correct_index) {
      setScore(prev => prev + 1);
    }
  };

  const handleNext = () => {
    if (!quiz) return;
    if (currentIdx < quiz.questions.length - 1) {
      setCurrentIdx(prev => prev + 1);
      setSelectedOpt(null);
      setIsChecked(false);
    } else {
      setQuizCompleted(true);
    }
  };

  const resetQuiz = () => {
    setCurrentIdx(0);
    setSelectedOpt(null);
    setIsChecked(false);
    setScore(0);
    setQuizCompleted(false);
    setQuizStarted(false);
    setQuiz(null);
  };

  if (!isLoggedIn) {
    return (
      <div className="bg-slate-900/40 border border-slate-800 rounded-2xl p-6 text-center mt-8">
        <h3 className="text-lg font-bold text-slate-200 mb-2">AI Self-Assessment</h3>
        <p className="text-sm text-slate-400 mb-4">Log in to your account to unlock the self-assessment quiz generated by Artificial Intelligence.</p>
        <Link href="/login" className="inline-block bg-cyan-600 hover:bg-cyan-500 text-white text-xs font-semibold py-2 px-5 rounded-full transition-all shadow-md">
          Log In
        </Link>
      </div>
    );
  }

  if (!quizStarted) {
    return (
      <div className="bg-slate-900/40 border border-slate-800 rounded-2xl p-6 text-center mt-8 hover:border-slate-700/80 transition-all">
        <h3 className="text-lg font-bold text-slate-200 mb-2 text-center">
          Lesson Self-Assessment
        </h3>
        <p className="text-xs text-slate-400 mb-5 max-w-md mx-auto">
          Finished reading? Test your retention with a dynamic 3-question quiz generated by AI based on this tutorial.
        </p>
        <button 
          onClick={fetchQuiz}
          className="bg-gradient-to-r from-cyan-600 to-cyan-500 hover:from-cyan-500 hover:to-cyan-400 text-white text-xs font-bold py-2.5 px-6 rounded-full transition-all shadow-lg hover:shadow-cyan-500/10 focus:outline-none"
        >
          Generate AI Quiz
        </button>
      </div>
    );
  }

  if (isLoading) {
    return (
      <div className="bg-slate-900/40 border border-slate-800 rounded-2xl p-8 text-center mt-8">
        <div className="flex flex-col items-center gap-4">
          <span className="animate-spin h-6 w-6 border-2 border-cyan-500 border-t-transparent rounded-full"></span>
          <span className="text-xs text-cyan-400 font-mono">Gemini is analyzing the lesson content for you...</span>
        </div>
      </div>
    );
  }

  if (error) {
    return (
      <div className="bg-slate-900/40 border border-rose-950/50 rounded-2xl p-6 text-center mt-8">
        <p className="text-xs text-rose-400 mb-4">{error}</p>
        <button 
          onClick={resetQuiz}
          className="text-xs text-slate-400 hover:text-white underline font-semibold transition-colors"
        >
          Try again
        </button>
      </div>
    );
  }

  if (quizCompleted && quiz) {
    const scorePercentage = Math.round((score / quiz.questions.length) * 100);
    return (
      <div className="bg-slate-900/40 border border-slate-800 rounded-2xl p-6 text-center mt-8">
        <div className="w-16 h-16 rounded-full bg-slate-950 border border-slate-800 flex items-center justify-center mx-auto mb-4">
          <span className={`font-bold text-lg ${scorePercentage >= 70 ? 'text-emerald-400' : 'text-yellow-500'}`}>
            {score}/{quiz.questions.length}
          </span>
        </div>
        <h3 className="text-lg font-bold text-slate-200 mb-1">
          {scorePercentage === 100 ? 'Perfect! Absolute Mastery' : scorePercentage >= 60 ? 'Good Job!' : 'Keep Learning'}
        </h3>
        <p className="text-xs text-slate-400 mb-5 max-w-sm mx-auto">
          You completed the quiz with a score of {scorePercentage}%. You can try again to reinforce your learning.
        </p>
        <div className="flex items-center justify-center gap-3">
          <button 
            onClick={resetQuiz}
            className="bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white text-xs font-semibold py-2 px-5 rounded-full transition-all border border-slate-700"
          >
            Retake Quiz
          </button>
        </div>
      </div>
    );
  }

  if (!quiz) return null;

  const currentQuestion = quiz.questions[currentIdx];
  const progressPercent = ((currentIdx + 1) / quiz.questions.length) * 100;

  return (
    <div className="bg-slate-900/40 border border-slate-800 rounded-2xl p-6 mt-8">
      {/* Progress Header */}
      <div className="mb-5">
        <div className="flex justify-between items-center text-[10px] text-slate-500 uppercase font-mono tracking-wider mb-2">
          <span>AI Assessment</span>
          <span>Question {currentIdx + 1} of {quiz.questions.length}</span>
        </div>
        <div className="w-full h-1 bg-slate-950 rounded-full overflow-hidden border border-slate-900/80">
          <div 
            className="h-full bg-cyan-500 transition-all duration-300"
            style={{ width: `${progressPercent}%` }}
          />
        </div>
      </div>

      {/* Question */}
      <h4 className="text-base font-bold text-slate-100 mb-5 leading-snug">
        {currentQuestion.question}
      </h4>

      {/* Options list */}
      <div className="flex flex-col gap-2.5 mb-5">
        {currentQuestion.options.map((option, idx) => {
          const isSelected = selectedOpt === idx;
          const isCorrect = idx === currentQuestion.correct_index;
          
          let btnStyle = "bg-slate-800/40 border-slate-800 hover:border-slate-700 text-slate-300 hover:text-white";
          
          if (isChecked) {
            if (isCorrect) {
              btnStyle = "bg-emerald-950/20 border-emerald-500/80 text-emerald-400 font-medium";
            } else if (isSelected) {
              btnStyle = "bg-rose-950/20 border-rose-500/80 text-rose-400 font-medium";
            } else {
              btnStyle = "bg-slate-900/20 border-slate-900/50 text-slate-600 cursor-not-allowed";
            }
          } else if (isSelected) {
            btnStyle = "bg-slate-800 border-cyan-500 text-white font-medium";
          }

          return (
            <button
              key={idx}
              onClick={() => handleOptionSelect(idx)}
              disabled={isChecked}
              className={`flex items-start text-left text-xs gap-3 p-3.5 rounded-xl border transition-all focus:outline-none ${btnStyle}`}
            >
              <span className={`flex items-center justify-center w-5 h-5 rounded-full border text-[10px] flex-shrink-0
                ${isSelected && !isChecked ? 'bg-cyan-500/20 border-cyan-400 text-cyan-400' : ''}
                ${isChecked && isCorrect ? 'bg-emerald-500/20 border-emerald-400 text-emerald-400' : ''}
                ${isChecked && isSelected && !isCorrect ? 'bg-rose-500/20 border-rose-400 text-rose-400' : ''}
                ${!isSelected && (!isChecked || !isCorrect) ? 'border-slate-700 text-slate-500' : ''}
              `}>
                {String.fromCharCode(65 + idx)}
              </span>
              <span className="leading-relaxed mt-0.5">{option}</span>
            </button>
          );
        })}
      </div>

      {/* Checked Answer Action & Explanation block */}
      {isChecked ? (
        <div className="bg-slate-950/30 border border-slate-800/80 rounded-xl p-4 mb-5 animate-fadeIn">
          <div className="flex items-center gap-2 mb-2">
            {selectedOpt === currentQuestion.correct_index ? (
              <>
                <svg className="w-4 h-4 text-emerald-500" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2.5} d="M5 13l4 4L19 7" />
                </svg>
                <span className="text-xs font-bold text-emerald-400">Correct!</span>
              </>
            ) : (
              <>
                <svg className="w-4 h-4 text-rose-500" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2.5} d="M6 18L18 6M6 6l12 12" />
                </svg>
                <span className="text-xs font-bold text-rose-400">Incorrect</span>
              </>
            )}
          </div>
          <p className="text-xs text-slate-400 leading-relaxed">
            {currentQuestion.explanation}
          </p>
        </div>
      ) : null}

      <div className="flex justify-end">
        {!isChecked ? (
          <button
            onClick={handleCheckAnswer}
            disabled={selectedOpt === null}
            className={`text-xs font-bold py-2 px-6 rounded-full transition-all focus:outline-none shadow-md
              ${selectedOpt === null 
                ? 'bg-slate-800 text-slate-500 border border-slate-800/40 cursor-not-allowed'
                : 'bg-cyan-600 hover:bg-cyan-500 text-white shadow-cyan-500/10'
              }
            `}
          >
            Check Answer
          </button>
        ) : (
          <button
            onClick={handleNext}
            className="bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white border border-slate-700 text-xs font-bold py-2 px-6 rounded-full transition-all focus:outline-none shadow-md"
          >
            {currentIdx < quiz.questions.length - 1 ? 'Next Question' : 'View Results'}
          </button>
        )}
      </div>
    </div>
  );
}
